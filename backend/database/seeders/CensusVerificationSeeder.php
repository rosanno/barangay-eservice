<?php

namespace Database\Seeders;

use App\Models\CensusCampaign;
use App\Models\Household;
use App\Models\HouseholdSurvey;
use App\Models\Resident; // ASSUMPTION: your existing residents model
use App\Models\User;
use Carbon\Carbon;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Str;

/**
 * Seeds an active census campaign with household surveys in every verification state,
 * so the Census Verification queue has realistic data to review.
 *
 *   php artisan db:seed --class=CensusVerificationSeeder
 *
 * Safe to re-run: it only adds surveys to targets that don't have one yet.
 */
class CensusVerificationSeeder extends Seeder
{
    /** How many surveys to create per status (takes the first unsurveyed targets). */
    private array $plan = [
        'draft' => 2,
        'for_verification' => 6,
        'needs_revision' => 1,
        'approved' => 2,
    ];

    public function run(): void
    {
        if (Household::count() === 0) {
            $this->command->warn('No households found. Seed households first, then run this seeder.');
            return;
        }

        $admin = User::where('role', 'admin')->first();
        $enumerators = User::where('role', 'staff')->get();
        if ($enumerators->isEmpty()) {
            $enumerators = collect([$this->makeUser('Test Enumerator', 'enumerator@brgy.test', 'staff')]);
            $this->command->info('Created staff user enumerator@brgy.test (password: password).');
        }

        /* ---- campaign ---- */
        $campaign = CensusCampaign::firstOrCreate(
            ['name' => 'Seeded Census Campaign (testing)'],
            [
                'description' => 'Sample campaign generated by CensusVerificationSeeder.',
                'start_date' => now()->subWeek()->toDateString(),
                'end_date' => now()->addMonth()->toDateString(),
                'status' => 'active',
                'created_by' => $admin?->id,
            ],
        );
        if ($campaign->status !== 'active') {
            $campaign->update(['status' => 'active']);
        }

        foreach (Household::whereNotNull('purok')->distinct()->pluck('purok') as $purok) {
            $campaign->puroks()->firstOrCreate(['purok' => $purok]);
        }
        $campaign->enumerators()->syncWithoutDetaching($enumerators->pluck('id')->all());
        $campaign->syncTargets();

        /* ---- surveys ---- */
        $targets = $campaign->targets()->whereDoesntHave('survey')->with('household')->orderBy('id')->get();
        $residents = $this->residentPool();
        $created = [];

        foreach ($this->plan as $status => $count) {
            for ($i = 0; $i < $count && $targets->isNotEmpty(); $i++) {
                $target = $targets->shift();
                $enumerator = $enumerators->random();
                $survey = $this->makeSurvey($campaign, $target, $enumerator, $status, $admin);
                $this->makeMembers($survey, $residents);

                if ($status === 'approved') {
                    $target->forceFill([
                        'status' => 'surveyed',
                        'surveyed_at' => $survey->verified_at,
                        'enumerator_id' => $enumerator->id,
                    ])->save();
                }
                $created[$status] = ($created[$status] ?? 0) + 1;
            }
        }

        $this->command->info('Census Verification seed complete: ' . json_encode($created));
        if ($targets->isEmpty() && array_sum($this->plan) > array_sum($created)) {
            $this->command->warn('Not enough households to reach the full plan; created what was available.');
        }
    }

    /* ---------- helpers ---------- */

    private function makeUser(string $name, string $email, string $role): User
    {
        return User::where('email', $email)->first() ?? tap((new User)->forceFill([
            'name' => $name,
            'email' => $email,
            'password' => Hash::make('password'),
            'role' => $role,
        ]))->save() ?: User::where('email', $email)->first();
    }

    private function pick(string $key): string
    {
        return array_rand(HouseholdSurvey::OPTIONS[$key]);
    }

    private function makeSurvey($campaign, $target, $enumerator, string $status, ?User $admin): HouseholdSurvey
    {
        $h = $target->household;
        $submitted = in_array($status, ['for_verification', 'needs_revision', 'approved'], true)
            ? now()->subHours(random_int(1, 96)) : null;

        $survey = new HouseholdSurvey([
            'household_number' => $h?->household_number,
            'head_name' => null, // set after members exist
            'address' => fake()->streetAddress(),
            'purok' => $h?->purok,
            'housing_type' => $this->pick('housing_type'),
            'ownership_status' => $this->pick('ownership_status'),
            'housing_condition' => $this->pick('housing_condition'),
            'water_source' => $this->pick('water_source'),
            'sanitation' => $this->pick('sanitation'),
            'has_electricity' => (bool) random_int(0, 4), // mostly yes
            'extra_answers' => [
                'is_4ps' => (bool) random_int(0, 1),
                'has_senior' => (bool) random_int(0, 1),
                'has_pwd' => false,
                'remarks' => random_int(0, 1) ? fake()->sentence() : null,
            ],
            'current_step' => $status === 'draft' ? random_int(1, 3) : 5,
        ]);

        $survey->forceFill([
            'census_campaign_id' => $campaign->id,
            'census_campaign_household_id' => $target->id,
            'household_id' => $target->household_id,
            'enumerator_id' => $enumerator->id,
            'status' => $status,
            'submitted_at' => $submitted,
        ]);

        if ($status === 'needs_revision') {
            $survey->forceFill([
                'verified_by' => $admin?->id,
                'verified_at' => now()->subHours(random_int(1, 24)),
                'verification_notes' => 'Please confirm the spelling of the household head\'s name and the birthdates of the children.',
                'revision_count' => 1,
            ]);
        }
        if ($status === 'approved') {
            $survey->forceFill([
                'verified_by' => $admin?->id,
                'verified_at' => now()->subHours(random_int(1, 24)),
                'verification_notes' => 'All details verified against resident records.',
            ]);
        }

        $survey->save();
        return $survey;
    }

    private function makeMembers(HouseholdSurvey $survey, $residents): void
    {
        $others = ['spouse', 'child', 'child', 'parent', 'sibling', 'grandchild'];
        shuffle($others);
        $relations = array_merge(['head'], array_slice($others, 0, random_int(1, 3)));

        foreach ($relations as $i => $relationship) {
            // linked = exact match, differs = linked but data differs, possible = unlinked duplicate, new = brand new
            $kind = collect(['linked', 'linked', 'differs', 'possible', 'new'])->random();
            if ($residents->isEmpty())
                $kind = 'new';
            $res = $kind !== 'new' ? $residents->shift() : null;
            if ($kind !== 'new' && !$res)
                $kind = 'new';

            $adult = in_array($relationship, ['head', 'spouse', 'parent'], true);
            $base = [
                'first_name' => fake('en_PH')->firstName(),
                'middle_name' => fake('en_PH')->lastName(),
                'last_name' => fake('en_PH')->lastName(),
                'suffix' => null,
                'sex' => random_int(0, 1) ? 'male' : 'female',
                'birthdate' => $adult
                    ? fake()->dateTimeBetween('-70 years', '-22 years')->format('Y-m-d')
                    : fake()->dateTimeBetween('-18 years', '-1 year')->format('Y-m-d'),
                'civil_status' => $adult ? $this->pick('civil_status') : 'single',
            ];

            $resident_id = null;
            if ($res) {
                $sex = strtolower((string) $this->scalar($res->sex ?? null));
                $civil = strtolower((string) $this->scalar($res->civil_status ?? null));
                $base = array_merge($base, array_filter([
                    'first_name' => $res->first_name,
                    'middle_name' => $res->middle_name,
                    'last_name' => $res->last_name,
                    'suffix' => $this->scalar($res->suffix ?? null),
                    'sex' => array_key_exists($sex, HouseholdSurvey::OPTIONS['sex']) ? $sex : null,
                    'birthdate' => $res->birthdate ? Carbon::parse($res->birthdate)->format('Y-m-d') : null,
                    'civil_status' => array_key_exists($civil, HouseholdSurvey::OPTIONS['civil_status']) ? $civil : null,
                ]));

                if ($kind === 'differs') { // typo'd surname + shifted birthdate → shows up as "differs from record"
                    $base['last_name'] = $base['last_name'] . 'e';
                    $base['birthdate'] = Carbon::parse($base['birthdate'])->addDays(random_int(1, 20))->format('Y-m-d');
                }
                $resident_id = $kind === 'possible' ? null : $res->id;
            }

            $employment = $adult ? $this->pick('employment_status') : 'student';
            $survey->members()->create(array_merge($base, [
                'client_key' => (string) Str::uuid(),
                'resident_id' => $resident_id,
                'is_new_resident' => $kind === 'new',
                'relationship' => $relationship,
                'education' => $adult ? $this->pick('education') : 'elementary',
                'employment_status' => $employment,
                'occupation' => in_array($employment, ['employed', 'self_employed'], true) ? fake()->jobTitle() : null,
                'is_pwd' => false,
                'is_registered_voter' => $adult && (bool) random_int(0, 1),
                'contact_number' => $adult ? '09' . random_int(100000000, 999999999) : null,
            ]));

            if ($relationship === 'head') {
                $survey->update(['head_name' => trim("{$base['first_name']} {$base['last_name']}")]);
            }
        }
    }

    /** Unwrap enum-cast attributes (e.g. App\Enums\Sex) into plain strings. */
    private function scalar($v)
    {
        if ($v instanceof \BackedEnum)
            return $v->value;
        if ($v instanceof \UnitEnum)
            return $v->name;
        return $v;
    }

    private function residentPool()
    {
        try {
            return Resident::inRandomOrder()->limit(80)->get();
        } catch (\Throwable) {
            return collect(); // residents table/model differs — everyone is seeded as a "new resident"
        }
    }
}